"""## Training Loop

### Training loop with Weights & Biases logging

Simply include `wandb.log()` at the end of each epoch to track metrics in real time.
"""

# Dynamically fetch number of epochs from config

from datetime import datetime

NUM_EPOCHS = config.epochs
train_losses = []
val_losses = []
train_ious = []
val_ious = []
val_precs = []
val_recs = []

# Initialize EarlyStopping helper with patience and path from config
early_stopping = EarlyStopping(
    patience=config["patience"], verbose=True, path="best_unet_pretrained.pth"
)

start = datetime.now()

for epoch in range(NUM_EPOCHS):
    # Record the start time of the epoch
    epoch_start = datetime.now()

    model.train()
    train_loss = 0
    train_iou = 0

    if torch.cuda.is_available():
        torch.cuda.empty_cache()

    for images, masks in train_loader:
        images = images.to(device)  # why not use device images again
        masks = masks.to(device)
        optimizer.zero_grad()

        outputs = model(images)
        loss = loss_function(outputs, masks)

        loss.backward()
        optimizer.step()

        train_loss += loss.item()
        train_iou += IoU(outputs, masks)

    avg_train_loss = train_loss / len(train_loader)
    avg_train_iou = train_iou / len(train_loader)
    train_losses.append(avg_train_loss)
    train_ious.append(avg_train_iou)

    # Validation Phase
    model.eval()
    val_loss = 0
    val_iou = 0
    val_prec = 0
    val_rec = 0
    with torch.no_grad():
        for images, masks in val_loader:
            images = images.to(device)
            masks = masks.to(device)

            outputs = model(images)
            loss = loss_function(outputs, masks)

            val_loss += loss.item()
            val_iou += IoU(outputs, masks)
            prec, rec = precision_recall(outputs, masks)
            val_prec += prec
            val_rec += rec

    avg_val_loss = val_loss / len(val_loader)
    avg_val_iou = val_iou / len(val_loader)
    avg_val_prec = val_prec / len(val_loader)
    avg_val_rec = val_rec / len(val_loader)
    val_losses.append(avg_val_loss)
    val_ious.append(avg_val_iou)
    val_precs.append(avg_val_prec)
    val_recs.append(avg_val_rec)

    # Calculate epoch duration in seconds
    epoch_duration = (datetime.now() - epoch_start).total_seconds()

    # Send metrics and epoch duration dynamically to Weights & Biases
    wandb.log(
        {
            "epoch": epoch + 1,
            "train/loss": avg_train_loss,
            "train/iou": avg_train_iou,
            "val/loss": avg_val_loss,
            "val/iou": avg_val_iou,
            "val/precision": avg_val_prec,
            "val/recall": avg_val_rec,
            "epoch/duration_sec": epoch_duration,
        }
    )

    print(
        f"Epoch {epoch + 1:02d} | Train Loss: {avg_train_loss:.4f} | Train IoU: {avg_train_iou:.4f} | "
        f"Val Loss: {avg_val_loss:.4f} | Val IoU: {avg_val_iou:.4f} | "
        f"Val P: {avg_val_prec:.3f} | Val R: {avg_val_rec:.3f} | Duration: {epoch_duration:.2f}s"
    )

    # Call EarlyStopping based on validation loss and validation IoU
    early_stopping(avg_val_loss, model, epoch + 1, optimizer, avg_val_iou)
    if early_stopping.early_stop:
        print("Early stopping triggered. Training stopped.")
        break

# Metrics of the best epoch (the one saved by early stopping) -> row for the noise floor table
